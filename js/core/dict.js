// Повторяемость. Каждый паттерн возвращает объект recurrence.
/** Основа названия дня недели -> индекс (0=вс). */
export function weekdayIndex(stem) {
  const map = { воскресень: 0, понедельник: 1, вторник: 2, сред: 3, четверг: 4, пятниц: 5, суббот: 6 };
  return map[stem] ?? 1;
}

